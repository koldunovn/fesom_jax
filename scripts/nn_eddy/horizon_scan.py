"""NN-GM Task 2 — the gradient-horizon scan (GATE HORIZON_OK).

Perfect-model twin on CORE2, no teacher data: a "truth" trajectory is generated by the
default all-on model with the GM κ-multiplier perturbed to ``m_true`` (default 1.25); the
student runs the same model at ``m=1`` from the same developed seed, and we measure the
health of ``d(Stage-1 loss)/d(m)`` as the window length N grows 1→10 days. The usable
horizon H (largest N with a clean, informative gradient) SETS the NG5 teacher snapshot
cadence: **cadence = min(H, 5) days** (plan Task 2 protocol rule).

Stage-1 loss form (plan Technical Details): per-level variance-weighted T,S + SSH misfit
at the target mark(s). Primary probe: ``--marks end`` — the loss at the single mark
t = N days, which isolates the N-day adjoint lag (daily marks inside a long window would
let early marks mask late-mark blow-up). ``--marks daily`` is the denser variant (marks at
every day-end; the first mark at 24 h already clears the 6–12 h nudge-in exclusion).

Health criteria per N (the longwindow C1 pattern, core2_lw_signflip.py):
  * finite, non-zero, |grad| below the blow-up guard (the real judge is the |grad|-vs-N
    curve: chaotic blow-up is orders of magnitude, cf. all3 adjoint 1e4→1e15);
  * FD sign agreement at the best h (secant FD across kinky limiters is noisy in
    magnitude — the SIGN is the trustworthy quantity);
  * INFORMATIVE: dL/dm < 0 at m=1 with truth at m_true=1.25 — the gradient points toward
    the truth κ.

Harness self-checks built in: the truth trajectory always runs NDAYS_TRUTH=10 days, so
the per-level variance weights are IDENTICAL across every (N, process); and
``loss(m_true) == 0`` exactly (same model, same seed, same code path) — a nonzero value
flags a plumbing bug, recorded as ``loss_at_truth``.

Config = the full paper config (zstar + TKE + mEVP + GM) with the FROZEN-ICE adjoint
(the mEVP rheology backward is the known dominant blow-up source; Stage-1 training will
use the same). The ``stop_gradient(ae)`` FCT-limiter escape hatch (docs/
LIMITER_GRADIENTS.md) is NOT yet config-wired — wire it only if this scan comes back
noisy (plan Task 2).

ONE (seed, N) per process (peak backward memory is a process-global high-water mark);
the .sbatch loops N. Usage (A100):
  python scripts/nn_eddy/horizon_scan.py --snap $WORK/port_jax/foundation_snaps/snap_step037440.pkl \\
      --season winterNH --n-days 3 --results scripts/nn_eddy/horizon_results.jsonl
"""

from __future__ import annotations

import argparse
import datetime
import json
import math
import os
import pickle
import re
import time
from pathlib import Path

import fesom_jax  # noqa: F401  (enables x64)
import jax
import jax.numpy as jnp
import numpy as np

from fesom_jax import ssh, surface_forcing
from fesom_jax.ale import AleConfig
from fesom_jax.calibrate import build_params
from fesom_jax.gm import GMConfig
