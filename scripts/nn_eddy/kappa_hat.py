"""NN-GM child-plan M3 — the κ̂ projection: turning the teacher's eddy fluxes into per-column
GM and Redi diffusivities, with a conditioning guard.

The coarse product stores, per node and layer, the coarse-grained eddy covariance
``uT_eddy = agg(u·T) − agg(u)·agg(T)`` (and the three siblings). This module asks: **what pair
of diffusivities would GM+Redi have needed to produce that flux?** The answer, per column, is
the Stage-0 fitting target.

The decomposition, and why density and spice
--------------------------------------------
For a tracer τ the GM+Redi horizontal eddy flux in the small-slope approximation is

    F_h(τ) = −K_Redi (∇_h τ + S ∂_z τ)  +  K_GM S ∂_z τ

with ``S`` the neutral slope. Apply that to DENSITY. By construction ``S = −∇_h σ / ∂_z σ``, so
``∇_h σ + S ∂_z σ ≡ 0``: **Redi does nothing to density**, which is the whole point of an
along-isopycnal operator. What is left is

    F_h(σ) = K_GM S ∂_z σ = −K_GM ∇_h σ      ⇒   κ̂_GM = −(F_σ · ∇_h σ) / |∇_h σ|²

so the density flux measures K_GM ALONE, with no contamination to subtract. Then take SPICE,
``χ = ρ0(αT + βS)`` — the tracer combination orthogonal to σ in the (αT, βS) plane, i.e. the
variation that does not change density. GM still acts on it (GM advects everything), so its
contribution is removed using the κ̂_GM just measured, and the residual is pure Redi:

    κ̂_Redi = −((F_χ − κ̂_GM S ∂_z χ) · ∇_iso χ) / |∇_iso χ|²,   ∇_iso χ = ∇_h χ + S ∂_z χ

**Nothing here re-derives σ or χ.** ``∇_h σ`` is ``gm.compute_sigma_xy``, the same array the GM
block itself uses; ``∇_h χ`` is the SAME function called with ``-T`` in place of ``T``, because
it computes ``ρ0(−α ∇T + β ∇S)`` and is linear in T, so flipping T's sign flips exactly the one
term that differs between density and spice. The α and β passed in are the real ones. That is
reuse, not a coincidence, and it means the two gradients share every masking and scatter
convention with the operator whose coefficient we are trying to recover.

Where this is approximate, stated up front
------------------------------------------
* ``S`` comes from ``compute_neutral_slope``, which builds the vertical part from the model's
  smoothed N² (full nonlinear EOS) while the horizontal part is the linearised ``sigma_xy``.
  So ``∇_h σ + S ∂_z σ`` is small but NOT identically zero, and the sequential
  density-then-spice projection is only as good as that residual. :func:`project` measures it
  (``b_sigma_frac``) instead of assuming it — if it is not small the two-target projection has
  to become a joint 2×2 least squares over both tracers.
* The eddy fluxes carry the coarse-graining's own ``elem_to_node`` non-conservative floor,
  ~1e-2 relative. "Recovers exactly" is therefore a claim about the SYNTHETIC test
  (:func:`synthetic_check`), where the fluxes are generated by the operator itself, and not
  about real products.
* Small-slope: the ``|S|²`` term in the Redi tensor's vertical row is dropped, as in the model.

The guard, and why it is two conditions
---------------------------------------
Rejecting on one statistic would hide the other failure. **Conditioning** — ``|∇σ|`` (or
``|∇_iso χ|``) too small — means the denominator is noise and κ̂ is a ratio of two small
numbers. **Adequacy** — the residual after the fit is a large fraction of the flux — means the
column's flux is simply not GM-like, so the projection returns a number that fits nothing. The
abyss fails the first and the tropics largely fail the second, and both fractions are reported
by depth band and latitude band because a fit trained on whatever survives is only meaningful
alongside a description of what did not.
"""

