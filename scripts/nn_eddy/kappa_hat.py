def report_by_stratum(mesh, d: _fp.Derived, kh: KappaHat, *, verbose: bool = True):
    """Kept/rejected fractions by depth band and latitude band.

    The plan predicts the abyss and the tropics will dominate the rejections; this is where
    that prediction is confirmed or not. A fit is only interpretable next to a statement of
    which ocean it was allowed to see."""
    nl = mesh.nl
    z = np.abs(np.asarray(mesh.Z))[None, :nl - 1] * np.ones((mesh.nod2D, 1))
    lat = _nd.geo_latitude_deg(mesh)[:, None] * np.ones((1, nl - 1))   # GEOGRAPHIC
    use = np.asarray(d.usable, bool)
    zb = [(0, 100), (100, 500), (500, 1500), (1500, 3000), (3000, 10000)]
    lb = [(-90, -60), (-60, -30), (-30, 30), (30, 60), (60, 90)]
    rows = []
    for lo, hi in zb:
        sel = use & (z >= lo) & (z < hi)
        n = int(sel.sum())
        rows.append(dict(kind="depth", band=f"{lo}-{hi} m", n=n,
                         kept_gm=float(np.asarray(kh.ok_gm)[sel].mean()) if n else float("nan"),
                         kept_redi=float(np.asarray(kh.ok_redi)[sel].mean()) if n
                         else float("nan")))
    for lo, hi in lb:
        sel = use & (lat >= lo) & (lat < hi)
        n = int(sel.sum())
        rows.append(dict(kind="lat", band=f"{lo}..{hi}", n=n,
                         kept_gm=float(np.asarray(kh.ok_gm)[sel].mean()) if n else float("nan"),
                         kept_redi=float(np.asarray(kh.ok_redi)[sel].mean()) if n
                         else float("nan")))
    if verbose:
        print("\n[strata] fraction of usable cells whose κ̂ survives the guard")
        print(f"  {'band':14s} {'n':>10s} {'kept GM':>9s} {'kept Redi':>10s}")
        for r in rows:
            print(f"  {r['band']:14s} {r['n']:>10d} {100*r['kept_gm']:8.1f}% "
                  f"{100*r['kept_redi']:9.1f}%")
    return rows


