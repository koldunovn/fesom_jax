def gm_redi_flux(mesh, d: _fp.Derived, k_gm, k_redi, *, gm_cfg: GMConfig = _fp.GM_CFG,
                 slope=None):
    """Forward operator: the horizontal GM+Redi eddy flux of T and S for given κ fields.

    ``F_h(τ) = −K_Redi (∇_h τ + S ∂_z τ) + K_GM S ∂_z τ`` applied to T and S separately, in
    the same small-slope form :func:`project` inverts.

    ⚠️ **The slope argument decides which of two different questions this answers, and the
    default is the inverse-problem one.** With ``slope=None`` it uses ``d.neutral_slope``, the
    UNTAPERED physical slope, matching :func:`project` — correct for :func:`synthetic_check`,
    where fluxes are generated and recovered through one operator so that the recovery has a
    known right answer, and correct for asking "what diffusivity would have produced this flux".

    It is NOT correct for asking "what flux would the student produce". The student applies the
    ODM95-tapered slope, and where stratification collapses the untapered slope diverges, so a
    predicted flux built on it is one the model would never generate: measured on 1958_06, it
    overshoots the teacher's flux by ~6 orders of magnitude and drives the explained variance to
    -2e+12. Any caller scoring a DEPLOYED closure must pass ``slope=d.slope_tapered[..., :2]``.
    """
    nl = mesh.nl
    slope = d.neutral_slope[..., :2] if slope is None else slope
    dT = to_layers(vertical_derivative(mesh, d.T), nl)
    dS = to_layers(vertical_derivative(mesh, d.S), nl)

    def one(tracer_grad_h, dtau):
        iso = tracer_grad_h + slope * dtau[..., None]
        return -k_redi[..., None] * iso + k_gm[..., None] * slope * dtau[..., None]

    gT = _tracer_gradient(mesh, d.T, gm_cfg)[:, :nl - 1, :]
    gS = _tracer_gradient(mesh, d.S, gm_cfg)[:, :nl - 1, :]
    return one(gT, dT), one(gS, dS)


def _tracer_gradient(mesh, X, gm_cfg: GMConfig):
    """``∇_h X`` for a single tracer, via ``compute_sigma_xy`` with α=0, β=1/ρ0.

    ``compute_sigma_xy(T, S, α, β)`` returns ``ρ0(−α∇T + β∇S)``; feeding the tracer as S with
    ``α = 0`` and ``β = 1/ρ0`` returns exactly ``∇X``. Same element→node area-weighted scatter
    and the same mask as the density gradient, which is the whole reason not to write a second
    gradient here."""
    zero = jnp.zeros_like(X)
    one_over_rho = jnp.full_like(X, 1.0 / gm_cfg.rho_ref)
    return gm.compute_sigma_xy(mesh, zero, X, zero, one_over_rho, gm_cfg)


def synthetic_check(mesh, d: _fp.Derived, *, seed: int = 0, verbose: bool = True):
    """Generate fluxes with the operator from a KNOWN κ(x,z), then recover both fields.

    This is the plan's required test and it is the only place "recovers exactly" can be
    claimed: real products carry the coarse-graining's ~1e-2 non-conservative floor, so a
    projection that failed on real data could always be blamed on the data. Here it cannot.

    The planted fields vary in BOTH space and depth and the two are given different patterns —
    a projection that recovered a single global constant, or that mixed the GM and Redi
    channels, would pass a constant-κ test and fail this one."""
    import jax
    nl = mesh.nl
    key = jax.random.PRNGKey(seed)
    # Rotated latitude on purpose: this is a SYNTHETIC κ field and `lat` is only being used
    # as a smooth spatial coordinate to vary it. Nothing here is labelled by region.
    lat = jnp.asarray(mesh.coord_nod2D)[:, 1][:, None]
    zl = jnp.abs(jnp.asarray(mesh.Z))[None, :nl - 1]
    k_gm_true = 300.0 + 700.0 * jnp.exp(-zl / 800.0) * (0.6 + 0.4 * jnp.cos(2.0 * lat))
    k_redi_true = 200.0 + 400.0 * jnp.exp(-zl / 1500.0) * (0.5 + 0.5 * jnp.sin(3.0 * lat))
    k_gm_true = jnp.broadcast_to(k_gm_true, (mesh.nod2D, nl - 1))
    k_redi_true = jnp.broadcast_to(k_redi_true, (mesh.nod2D, nl - 1))

    F_T, F_S = gm_redi_flux(mesh, d, k_gm_true, k_redi_true)
    kh = project(mesh, d, F_T, F_S, verbose=False)

    out = {}
    for name, got, want, ok in (("kappa_gm", kh.kappa_gm, k_gm_true, kh.ok_gm),
                                ("kappa_redi", kh.kappa_redi, k_redi_true, kh.ok_redi)):
        m = np.asarray(ok, bool)
        g, w = np.asarray(got)[m], np.asarray(want)[m]
        rel = np.abs(g - w) / np.maximum(np.abs(w), 1e-300)
        out[name] = dict(n=int(m.sum()), median_rel=float(np.median(rel)) if m.sum() else
                         float("nan"),
                         p99_rel=float(np.percentile(rel, 99)) if m.sum() else float("nan"),
                         max_rel=float(rel.max()) if m.sum() else float("nan"))
    if verbose:
        print("[synthetic] fluxes generated by the operator from a known κ(x,z); recovery:")
        for k, v in out.items():
            print(f"  {k:11s} n={v['n']:>9d}  median rel {v['median_rel']:.3e}  "
                  f"p99 {v['p99_rel']:.3e}  max {v['max_rel']:.3e}")
        print("  (anything above round-off is the decoupling residual b_sigma, not the "
              "projection algebra)", flush=True)
    return out


