def load_fluxes(path: Path, record: int, nl: int):
    """``(F_T, F_S)`` model-shaped ``(N, nl-1, 2)`` from one record of a coarse product."""
    import netCDF4
    with netCDF4.Dataset(path) as ds:
        get = lambda n: _fp.expand_levels(  # noqa: E731
            np.asarray(ds.variables[n][record], np.float64), nl)[:, :nl - 1]
        F_T = np.stack([get("uT_eddy"), get("vT_eddy")], axis=-1)
        F_S = np.stack([get("uS_eddy"), get("vS_eddy")], axis=-1)
    return jnp.asarray(F_T), jnp.asarray(F_S)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--month", default="1958_06")
    ap.add_argument("--record", type=int, default=0)
    ap.add_argument("--coarse-dir", type=Path, default=_nd.COARSE_DIR)
    ap.add_argument("--grad-floor", type=float, default=GRAD_FLOOR)
    ap.add_argument("--slope-floor", type=float, default=SLOPE_FLOOR)
    ap.add_argument("--resid-max", type=float, default=RESID_MAX)
    ap.add_argument("--synthetic", action="store_true",
                    help="also run the operator-generated recovery test on this state")
    args = ap.parse_args()

    t0 = time.time()
    mesh = load_mesh(_fp.MESH_DIR)
    p = Path(args.coarse_dir) / f"coarse_ng5_{args.month}.nc"
    T47, S47, have47, tsec = _fp.load_product_mark(p, args.record)
    print(f"[product] {p.name} record {args.record}: mark {_nd.mark_index(tsec)}", flush=True)
    d = _fp.derive(mesh, T47, S47, have47)
    F_T, F_S = load_fluxes(p, args.record, mesh.nl)

    kh = project(mesh, d, F_T, F_S, grad_floor=args.grad_floor, slope_floor=args.slope_floor,
                 resid_max=args.resid_max)
    report_by_stratum(mesh, d, kh)

    # the distributions the provisional floors must eventually be frozen from
    use = np.asarray(d.usable, bool)
    print("\n[distributions] over usable wet layer cells — freeze the floors from these")
    for nm, arr in (("|grad_sigma| [kg/m^4]", kh.grad_sigma),
                    ("|grad_iso_chi| [kg/m^4]", kh.grad_iso_chi),
                    ("resid_gm", kh.resid_gm), ("resid_redi", kh.resid_redi)):
        v = np.asarray(arr)[use]
        q = np.percentile(v, [1, 10, 25, 50, 75, 90, 99])
        print(f"  {nm:24s} " + "  ".join(f"p{p_:02d}={x:.3e}"
                                         for p_, x in zip([1, 10, 25, 50, 75, 90, 99], q)))
    for nm, arr, ok in (("kappa_gm [m^2/s]", kh.kappa_gm, kh.ok_gm),
                        ("kappa_redi [m^2/s]", kh.kappa_redi, kh.ok_redi)):
        v = np.asarray(arr)[np.asarray(ok, bool)]
        if v.size:
            q = np.percentile(v, [1, 10, 50, 90, 99])
            print(f"  {nm:24s} " + "  ".join(f"p{p_:02d}={x:+.4g}"
                                             for p_, x in zip([1, 10, 50, 90, 99], q)))
    # what fraction of the target is even reachable by a bounded multiplier?
    for nm, kap, base, ok in (("GM", kh.kappa_gm, np.asarray(d.fer_K_lay), kh.ok_gm),
                              ("Redi", kh.kappa_redi, np.asarray(d.Ki)[:, :mesh.nl - 1],
                               kh.ok_redi)):
        m = np.asarray(ok, bool) & (base > 0)
        r = np.asarray(kap)[m] / base[m]
        inb = float(np.mean((r >= 1 / 3) & (r <= 3.0))) if r.size else float("nan")
        print(f"  {nm:4s} ratio κ̂/κ_formula: median {np.median(r):+.3f}, "
              f"{100*inb:.1f}% inside the [1/3, 3] multiplier bound "
              f"({100*float(np.mean(r < 0)):.1f}% negative)")

    if args.synthetic:
        synthetic_check(mesh, d)
    print(f"\n[done] {time.time()-t0:.1f}s", flush=True)


if __name__ == "__main__":
    main()
