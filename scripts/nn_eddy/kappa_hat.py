# ~2e-6 kg/m^4 at α = 2e-4 /K, so 1e-7 is roughly a 0.05 K / 100 km front — comfortably below
# anything the mesoscale carries and well above round-off.
GRAD_FLOOR = 1.0e-7          # kg/m^4
SLOPE_FLOOR = 1.0e-5         # |S|, dimensionless; below this GM has no isopycnal to act on
RESID_MAX = 0.5              # rejected if the fit leaves > this fraction of |F| unexplained

# ⚠️ THE CONDITION THAT ACTUALLY MATTERS, and it is not the obvious one.
#
# ``b_sigma = ∇_h σ + S ∂_z σ`` is zero in exact arithmetic, which is what makes Redi blind to
# density and lets κ̂_GM be read straight off the density flux. Here it is not exactly zero: the
# slope's vertical part comes from the model's SMOOTHED, fully nonlinear N² while its horizontal
# part is the linearised ``sigma_xy``. Where the two disagree, Redi's density flux
# ``−K_Redi·b_sigma`` is not negligible — and, because ``b_sigma`` is COLLINEAR with ``∇σ``, it
# lands entirely in κ̂_GM's magnitude.
#
# That collinearity is why the residual test cannot see this failure. Measured on the synthetic
# recovery: cells that come back wrong have ``resid_gm`` = 1.5e-16 against 1.4e-16 for cells
# that come back right — indistinguishable — while ``b_sigma_frac`` reads 9.2e+02 against
# 6.6e-03, five orders of magnitude apart. A perpendicular-residual check on a contamination
# that is parallel is structurally blind, not merely weak.
#
# The cut sits in a measured EMPTY GAP: raising it from 0.1 to 0.3 changes nothing (93.4% kept
# either way), and at 0.1 the synthetic recovery is median 2.2e-3, p99 1.5e-2, max 3.5e-2
# relative — below the coarse-graining's own ~1e-2 non-conservative floor.
B_SIGMA_MAX = 0.1


def vertical_derivative(mesh, field, Z3d=None):
    """``∂X/∂z`` at INTERFACES from a layer field, using the model's own column spacing.

    ``out[:, k] = (X[k-1] − X[k]) / (Z[k-1] − Z[k])``, edge-replicated at the surface exactly
    as :func:`fesom_jax.eos.pressure_bv` does when it builds N² — same operator, so
    ``-(g/ρ0)·∂σ/∂z`` from here and ``bvfreq`` differ only by the EOS linearisation and the N²
    smoother, which is a difference worth being able to measure (:func:`project` does)."""
    from fesom_jax.eos import _shift_down
    if Z3d is None:
        Zp = jnp.concatenate([mesh.Z, mesh.Z[-1:]])
        z = Zp[None, :]
    else:
        z = jnp.asarray(Z3d)
    zdiff = _shift_down(z) - z
    zdiff = jnp.where(zdiff == 0.0, 1.0, zdiff)      # unused surface/bottom interfaces
    x = jnp.asarray(field)
    return (_shift_down(x) - x) / zdiff


def to_layers(iface_field, nl):
    """Interface field ``(N, nl)`` → layer centres ``(N, nl-1)``, the same average
    :func:`fesom_jax.gm.gm_nn_features` uses for N². One convention, stated once."""
    return 0.5 * (iface_field[:, :nl - 1] + iface_field[:, 1:nl])


@dataclasses.dataclass
class KappaHat:
    """Per-node/layer diffusivities implied by the teacher's eddy fluxes, plus the guard."""
    kappa_gm: np.ndarray        # (N, nl-1)  [m^2/s]
    kappa_redi: np.ndarray      # (N, nl-1)  [m^2/s]
    ok_gm: np.ndarray           # (N, nl-1) bool — passed conditioning AND adequacy
    ok_redi: np.ndarray
    grad_sigma: np.ndarray      # (N, nl-1) |∇_h σ|
    grad_iso_chi: np.ndarray    # (N, nl-1) |∇_iso χ|
    resid_gm: np.ndarray        # (N, nl-1) unexplained fraction of |F_σ|
    resid_redi: np.ndarray
    b_sigma_frac: np.ndarray    # (N, nl-1) |∇σ + S ∂_zσ| / |∇σ| — the decoupling residual
    reject: dict                # reason → count


def project(mesh, d: _fp.Derived, F_T, F_S, *, gm_cfg: GMConfig = _fp.GM_CFG,
            grad_floor: float = GRAD_FLOOR, slope_floor: float = SLOPE_FLOOR,
            resid_max: float = RESID_MAX, b_sigma_max: float = B_SIGMA_MAX,
            verbose: bool = True) -> KappaHat:
    """κ̂_GM and κ̂_Redi per column from the eddy fluxes ``F_T``, ``F_S``.

    ``F_T``/``F_S`` are ``(N, nl-1, 2)`` model-shaped horizontal eddy fluxes of T and S
    (``uT_eddy``/``vT_eddy`` and the salinity pair), in the layer range. ``d`` is the derived
    bundle from :func:`features_from_product.derive` on the SAME mark — same T, same S, same
    hole fill, so the gradients and the fluxes describe one ocean."""
    nl = mesh.nl
    T, S = d.T, d.S
    a, b = d.sw_alpha, d.sw_beta
    rho0 = gm_cfg.rho_ref

    # --- horizontal gradients of density and spice ---------------------------
    # compute_sigma_xy returns rho0(-a*grad T + b*grad S). Linear in T, so passing -T returns
    # rho0(+a*grad T + b*grad S) = grad(spice). Same scatter, same masking, one implementation.
    grad_sig = d.sigma_xy[:, :nl - 1, :]                              # (N,nl-1,2)
    grad_chi = gm.compute_sigma_xy(mesh, -T, S, a, b, gm_cfg)[:, :nl - 1, :]

    # --- vertical derivatives at layer centres -------------------------------
    dT = to_layers(vertical_derivative(mesh, T), nl)
    dS = to_layers(vertical_derivative(mesh, S), nl)
    # α and β are LAYER fields already (compute_sw_alpha_beta maps layer T,S), so they are
    # trimmed, never averaged — averaging them would smear the EOS coefficients across layers.
    a_l, b_l = a[:, :nl - 1], b[:, :nl - 1]
    dsig = rho0 * (-a_l * dT + b_l * dS)                              # ∂σ/∂z at layer centres
    dchi = rho0 * (a_l * dT + b_l * dS)

    # ⚠️ The UNTAPERED neutral slope, deliberately. The ODM95 taper is a numerical safety
    # device in the STUDENT's operator; the teacher is an eddy-resolving ocean and its fluxes
    # know nothing about it. So "what diffusivity would have produced this flux" is asked with
    # the physical slope, and the taper stays where it belongs — inside the formula base κ that
    # the fitted ratio is taken against. The consequence is real and reported by the CLI: where
    # the taper has crushed the base, the ratio κ̂/κ_base can leave the [1/3, 3] multiplier
    # bound, and a bounded multiplier simply cannot reach that column.
    slope = d.neutral_slope[..., :2]                                  # (N,nl-1,2)
    smag = d.neutral_slope[..., 2]

    # --- the decoupling residual: is Redi really blind to density here? ------
    # b_sigma = grad_h(sigma) + S*d_z(sigma). Zero in exact arithmetic; nonzero here because
    # the slope's vertical part comes from the smoothed nonlinear-EOS N2 while its horizontal
    # part is the linearised sigma_xy. If this is not small, the sequential projection below
    # has to become a joint 2x2 least squares. Measured, not assumed.
    b_sig = grad_sig + slope * dsig[..., None]
    gs = _norm(grad_sig)
    b_sigma_frac = _norm(b_sig) / jnp.maximum(gs, 1e-300)

    # --- eddy fluxes of density and spice ------------------------------------
    F_sig = rho0 * (-a_l[..., None] * F_T + b_l[..., None] * F_S)
    F_chi = rho0 * (a_l[..., None] * F_T + b_l[..., None] * F_S)

    # --- kappa_GM from density: F_sig = -k * grad_sigma ----------------------
    k_gm = -_dot(F_sig, grad_sig) / jnp.maximum(gs ** 2, 1e-300)
    resid_gm = _norm(F_sig + k_gm[..., None] * grad_sig) / jnp.maximum(_norm(F_sig), 1e-300)

    # --- kappa_Redi from spice, after removing GM's share --------------------
    gm_share = k_gm[..., None] * slope * dchi[..., None]              # +K_GM S d_z chi
    grad_iso_chi = grad_chi + slope * dchi[..., None]
    gi = _norm(grad_iso_chi)
    F_redi = F_chi - gm_share
    k_redi = -_dot(F_redi, grad_iso_chi) / jnp.maximum(gi ** 2, 1e-300)
    resid_redi = (_norm(F_redi + k_redi[..., None] * grad_iso_chi)
                  / jnp.maximum(_norm(F_redi), 1e-300))

    # --- the guard -----------------------------------------------------------
    use = jnp.asarray(d.usable, bool)
    cond_gm = gs >= grad_floor
    cond_redi = gi >= grad_floor
    has_slope = smag >= slope_floor
    # The decoupled condition — see B_SIGMA_MAX. This is the one that actually separates the
    # cells that recover from the ones that do not, and the residual test cannot substitute
    # for it because the contamination it catches is COLLINEAR with ∇σ and therefore invisible
    # to a perpendicular-residual check.
    decoupled = b_sigma_frac <= b_sigma_max
    ok_gm = (use & cond_gm & has_slope & decoupled & (resid_gm <= resid_max)
             & jnp.isfinite(k_gm))
    ok_redi = (use & cond_redi & has_slope & decoupled & (resid_redi <= resid_max)
               & jnp.isfinite(k_redi))

    nwet = int(jnp.sum(use))
    rej = dict(
        wet_layer_cells=nwet,
        not_usable_hole_ring=int(jnp.sum(jnp.asarray(d.lay, bool) & ~use)),
        gm_illconditioned=int(jnp.sum(use & ~cond_gm)),
        gm_no_slope=int(jnp.sum(use & cond_gm & ~has_slope)),
        not_decoupled=int(jnp.sum(use & cond_gm & has_slope & ~decoupled)),
        gm_inadequate=int(jnp.sum(use & cond_gm & has_slope & decoupled
                                  & (resid_gm > resid_max))),
        redi_illconditioned=int(jnp.sum(use & ~cond_redi)),
        redi_inadequate=int(jnp.sum(use & cond_redi & has_slope & decoupled
                                    & (resid_redi > resid_max))),
        kept_gm=int(jnp.sum(ok_gm)), kept_redi=int(jnp.sum(ok_redi)),
        negative_kappa_gm=int(jnp.sum(ok_gm & (k_gm < 0.0))),
        negative_kappa_redi=int(jnp.sum(ok_redi & (k_redi < 0.0))),
    )
    if verbose:
        print(f"[kappa] {nwet} usable wet layer cells")
        print(f"  GM   kept {rej['kept_gm']:>9d} ({100*rej['kept_gm']/max(nwet,1):5.1f}%)  "
              f"rejected: ill-conditioned {rej['gm_illconditioned']}, "
              f"no slope {rej['gm_no_slope']}, Redi not decoupled from density "
              f"{rej['not_decoupled']}, flux not GM-like {rej['gm_inadequate']}")
        print(f"  Redi kept {rej['kept_redi']:>9d} ({100*rej['kept_redi']/max(nwet,1):5.1f}%)  "
              f"rejected: ill-conditioned {rej['redi_illconditioned']}, "
              f"flux not Redi-like {rej['redi_inadequate']}")
        print(f"  UP-gradient (kappa<0, real but NOT representable by a positive bounded "
              f"multiplier): GM {rej['negative_kappa_gm']} "
              f"({100*rej['negative_kappa_gm']/max(rej['kept_gm'],1):.1f}% of kept), "
              f"Redi {rej['negative_kappa_redi']} "
              f"({100*rej['negative_kappa_redi']/max(rej['kept_redi'],1):.1f}%)")
        bs = np.asarray(b_sigma_frac)[np.asarray(use)]
        print(f"  decoupling residual |∇σ+S∂zσ|/|∇σ|: median {np.median(bs):.3e}, "
              f"p90 {np.percentile(bs, 90):.3e}  "
              f"— the sequential projection is only as good as this", flush=True)
    return KappaHat(kappa_gm=np.asarray(k_gm), kappa_redi=np.asarray(k_redi),
                    ok_gm=np.asarray(ok_gm), ok_redi=np.asarray(ok_redi),
                    grad_sigma=np.asarray(gs), grad_iso_chi=np.asarray(gi),
                    resid_gm=np.asarray(resid_gm), resid_redi=np.asarray(resid_redi),
                    b_sigma_frac=np.asarray(b_sigma_frac), reject=rej)


def _norm(v):
    return jnp.sqrt(jnp.maximum(v[..., 0] ** 2 + v[..., 1] ** 2, 0.0))


def _dot(u, v):
    return u[..., 0] * v[..., 0] + u[..., 1] * v[..., 1]


